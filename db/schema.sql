CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL UNIQUE, pin_hash TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'cashier', active INTEGER NOT NULL DEFAULT 1, must_change INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS drugs (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT, arabic TEXT, active TEXT, company TEXT,
  price REAL NOT NULL DEFAULT 0, old_price REAL, cost REAL NOT NULL DEFAULT 0,
  barcode TEXT, units INTEGER, strips INTEGER NOT NULL DEFAULT 1,
  category TEXT, uses TEXT, min_qty REAL NOT NULL DEFAULT 0,
  is_custom INTEGER NOT NULL DEFAULT 0, kind TEXT NOT NULL DEFAULT 'drug',
  search TEXT
);
CREATE INDEX IF NOT EXISTS ix_drugs_barcode ON drugs(barcode);
CREATE INDEX IF NOT EXISTS ix_drugs_active ON drugs(active);
CREATE TABLE IF NOT EXISTS batches (
  id INTEGER PRIMARY KEY AUTOINCREMENT, drug_id INTEGER NOT NULL, batch_no TEXT NOT NULL DEFAULT '',
  expiry TEXT, qty REAL NOT NULL DEFAULT 0, cost REAL NOT NULL DEFAULT 0, price REAL,
  purchase_id INTEGER, created_at TEXT
);
CREATE INDEX IF NOT EXISTS ix_batches_drug ON batches(drug_id);
CREATE TABLE IF NOT EXISTS suppliers (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, phone TEXT, balance REAL NOT NULL DEFAULT 0, note TEXT);
CREATE TABLE IF NOT EXISTS customers (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, phone TEXT, balance REAL NOT NULL DEFAULT 0, note TEXT, chronic TEXT);
CREATE TABLE IF NOT EXISTS purchases (
  id INTEGER PRIMARY KEY AUTOINCREMENT, supplier_id INTEGER, date TEXT, invoice_no TEXT,
  total REAL NOT NULL DEFAULT 0, paid REAL NOT NULL DEFAULT 0, note TEXT, user_id INTEGER
);
CREATE TABLE IF NOT EXISTS purchase_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT, purchase_id INTEGER NOT NULL, drug_id INTEGER NOT NULL, batch_id INTEGER,
  batch_no TEXT, expiry TEXT, qty REAL NOT NULL, cost REAL NOT NULL, price REAL
);
CREATE TABLE IF NOT EXISTS shifts (
  id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER, opened_at TEXT, opening_cash REAL NOT NULL DEFAULT 0,
  closed_at TEXT, expected_cash REAL, counted_cash REAL, note TEXT
);
CREATE TABLE IF NOT EXISTS sales (
  id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT NOT NULL, user_id INTEGER, shift_id INTEGER, customer_id INTEGER,
  subtotal REAL NOT NULL, discount REAL NOT NULL DEFAULT 0, total REAL NOT NULL,
  cash REAL NOT NULL DEFAULT 0, card REAL NOT NULL DEFAULT 0, credit REAL NOT NULL DEFAULT 0,
  cost_total REAL NOT NULL DEFAULT 0, note TEXT, delivery INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_sales_date ON sales(date);
CREATE TABLE IF NOT EXISTS sale_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT, sale_id INTEGER NOT NULL, drug_id INTEGER NOT NULL, batch_id INTEGER,
  qty REAL NOT NULL, unit TEXT NOT NULL DEFAULT 'pack', price REAL NOT NULL, cost REAL NOT NULL DEFAULT 0,
  discount REAL NOT NULL DEFAULT 0, total REAL NOT NULL, returned_qty REAL NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_sale_items_sale ON sale_items(sale_id);
CREATE TABLE IF NOT EXISTS sale_returns (
  id INTEGER PRIMARY KEY AUTOINCREMENT, sale_id INTEGER, date TEXT, user_id INTEGER, shift_id INTEGER, total REAL NOT NULL, cost_total REAL NOT NULL DEFAULT 0, refund TEXT, note TEXT
);
CREATE TABLE IF NOT EXISTS payments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT, party_type TEXT NOT NULL, party_id INTEGER NOT NULL,
  amount REAL NOT NULL, user_id INTEGER, shift_id INTEGER, note TEXT
);
CREATE TABLE IF NOT EXISTS expenses (
  id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT, category TEXT, amount REAL NOT NULL, note TEXT, user_id INTEGER, shift_id INTEGER
);
CREATE TABLE IF NOT EXISTS stock_adjustments (
  id INTEGER PRIMARY KEY AUTOINCREMENT, date TEXT, drug_id INTEGER, batch_id INTEGER, old_qty REAL, new_qty REAL, reason TEXT, user_id INTEGER
);
